// 默认中文；检测系统语言但 zh 场景一律回落 zh-CN
function detectLocale() {
  const lang = navigator.language || 'zh-CN'
  return lang.toLowerCase().startsWith('zh') ? 'zh-CN' : lang.toLowerCase().startsWith('en') ? 'en-US' : 'zh-CN'
}

const state = reactive({
  locale: localStorage.getItem('dm-locale') || detectLocale()
})

export function setLocale(locale) {
  if (dictionaries[locale]) {
    state.locale = locale
    localStorage.setItem('dm-locale', locale)
  }
}

export function useI18n() {
  const t = (key, params) => {
    let text = dictionaries[state.locale]?.[key] ?? dictionaries['zh-CN'][key] ?? key
    if (params) {
      for (const [k, v] of Object.entries(params)) text = text.replace(`{${k}}`, v)
    }
    return text
  }
  return { t, state, setLocale, locales: Object.keys(dictionaries) }
}
